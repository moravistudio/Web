/*
 * Ventana de chat con IA (widget). Se instala con una sola etiqueta en la página del negocio:
 *   <script src=".../chatbot-ia.js" data-cliente="moravi-studio" data-api="https://servidor" data-titulo="Asistente de Moravi Studio" defer></script>
 * (el CSS se carga solo). No contiene ninguna clave: habla con el servidor propio, que es el único que usa la IA.
 * El texto de los mensajes se inserta siempre como texto (nunca como HTML) y solo se convierten en enlaces las direcciones http(s).
 * Idioma: sigue el atributo lang de <html> (es / en) y cambia en vivo si la página cambia de idioma.
 * También se puede montar DENTRO de la página (sin globo flotante), para las páginas de demos:
 *   MsiaChat.mount({ contenedor: elemento, cliente: 'demo-contable', api: 'https://servidor', titulo: '...', bienvenida: '...', pie: '...' })
 */
(function () {
  'use strict';
  var scriptEl = document.currentScript, scriptSrc = scriptEl ? scriptEl.src : '';

  // me = algo con getAttribute('data-...') y src (la etiqueta <script> o un objeto armado por mount); contenedor = si se monta dentro de la página
  function create(me, contenedor) {
    var cliente = me.getAttribute('data-cliente'), api = (me.getAttribute('data-api') || '').replace(/\/$/, '');
    var whatsapp = me.getAttribute('data-whatsapp') || '';
    if (!cliente || !api) return null;
    var embed = !!contenedor;
    var base = (me.src || '').replace(/[^\/]*$/, '');
    if (!document.getElementById('msia-css')) { var css = document.createElement('link'); css.id = 'msia-css'; css.rel = 'stylesheet'; css.href = base + 'chatbot-ia.css'; document.head.appendChild(css); }

    var TX = {
      es: {
        titulo: me.getAttribute('data-titulo') || 'Asistente virtual',
        sub: me.getAttribute('data-sub') || 'Asistente con IA',
        bienvenida: me.getAttribute('data-bienvenida') || '¡Hola! Soy el asistente virtual con IA. Pregúntame lo que quieras sobre nuestros servicios 😊',
        abrir: 'Abrir chat', cerrar: 'Cerrar chat', nuevo: 'Nueva conversación', tuMensaje: 'Tu mensaje', placeholder: 'Escribe tu pregunta…', enviar: 'Enviar',
        pie: me.getAttribute('data-pie') || 'Las respuestas las genera una IA; confirma los datos importantes con el negocio.', escribiendo: 'Escribiendo',
        privacidad: 'Privacidad',
        wa: ' Escríbenos por WhatsApp: ',
        limConv: 'Llegamos al límite de esta conversación. Pulsa ↻ para empezar otra.',
        rapido: 'Estás escribiendo muy rápido. Espera unos segundos e inténtalo de nuevo.',
        limDia: 'Por hoy ya no puedo responder más mensajes.',
        largo: function (n) { return 'Tu mensaje es muy largo. Prueba con algo más corto (máximo ' + n + ' caracteres).'; },
        fallo: 'No pude responder en este momento. Inténtalo de nuevo en un momento.',
        conexion: 'No pude conectarme. Revisa tu conexión e inténtalo de nuevo.'
      },
      en: {
        titulo: me.getAttribute('data-titulo-en') || me.getAttribute('data-titulo') || 'Virtual assistant',
        sub: me.getAttribute('data-sub-en') || me.getAttribute('data-sub') || 'AI assistant',
        bienvenida: me.getAttribute('data-bienvenida-en') || 'Hi! I\'m the AI virtual assistant. Ask me anything about our services 😊',
        abrir: 'Open chat', cerrar: 'Close chat', nuevo: 'New conversation', tuMensaje: 'Your message', placeholder: 'Type your question…', enviar: 'Send',
        pie: me.getAttribute('data-pie-en') || 'Answers are generated by AI; please confirm important details with the business.', escribiendo: 'Typing',
        privacidad: 'Privacy',
        wa: ' Message us on WhatsApp: ',
        limConv: 'We\'ve reached the limit of this conversation. Press ↻ to start a new one.',
        rapido: 'You\'re typing too fast. Wait a few seconds and try again.',
        limDia: 'I can\'t answer more messages for today.',
        largo: function (n) { return 'Your message is too long. Try something shorter (max ' + n + ' characters).'; },
        fallo: 'I couldn\'t answer right now. Please try again in a moment.',
        conexion: 'I couldn\'t connect. Check your connection and try again.'
      }
    };
    function lang() { return String(document.documentElement.getAttribute('lang') || 'es').toLowerCase().indexOf('en') === 0 ? 'en' : 'es'; }
    function tx(k) { return TX[lang()][k]; }

    var KEY = 'msia-' + cliente, MAX_CHARS = +me.getAttribute('data-max') || 500, msgs = [], busy = false;
    try { msgs = JSON.parse(sessionStorage.getItem(KEY) || '[]').filter(function (m) { return m && (m.rol === 'user' || m.rol === 'assistant') && typeof m.texto === 'string'; }).slice(-40); } catch (e) { msgs = []; }
    function save() { try { sessionStorage.setItem(KEY, JSON.stringify(msgs.slice(-40))); } catch (e) { /* sin almacenamiento: la conversación vive solo en pantalla */ } }

    function el(tag, cls, txt) { var e = document.createElement(tag); if (cls) e.className = cls; if (txt != null) e.textContent = txt; return e; }
    var root = el('div', 'msia-root' + (embed ? ' msia-embed is-open' : '')), toggle = el('button', 'msia-toggle'), win = el('div', 'msia-win'), list = el('div', 'msia-msgs'), form = el('form', 'msia-form'), input = el('textarea', 'msia-input'), send = el('button', 'msia-send');
    toggle.type = 'button'; toggle.setAttribute('aria-expanded', embed ? 'true' : 'false');
    toggle.innerHTML = '<svg viewBox="0 0 24 24" fill="#fff" aria-hidden="true"><path d="M21 15a2 2 0 0 1-2 2H7l-4 4V5a2 2 0 0 1 2-2h14a2 2 0 0 1 2 2z"/></svg>';
    win.setAttribute('role', 'dialog');
    var head = el('div', 'msia-head'), t = el('b'), tTitulo = document.createTextNode(''), sub = el('small'); t.appendChild(tTitulo); t.appendChild(sub);
    var nuevo = el('button', 'msia-icon-btn', '↻'); nuevo.type = 'button';
    var cerrar = el('button', 'msia-icon-btn', '✕'); cerrar.type = 'button';
    head.appendChild(t); head.appendChild(nuevo); if (!embed) head.appendChild(cerrar);
    input.rows = 1; input.maxLength = MAX_CHARS; send.type = 'submit';
    form.appendChild(input); form.appendChild(send);
    var foot = el('div', 'msia-foot');
    win.appendChild(head); win.appendChild(list); win.appendChild(form); win.appendChild(foot); root.appendChild(win); root.appendChild(toggle);

    function textos() {
      tTitulo.nodeValue = tx('titulo'); sub.textContent = tx('sub'); win.setAttribute('aria-label', tx('titulo'));
      toggle.setAttribute('aria-label', tx('abrir')); nuevo.title = tx('nuevo'); nuevo.setAttribute('aria-label', tx('nuevo')); cerrar.setAttribute('aria-label', tx('cerrar'));
      input.placeholder = tx('placeholder'); input.setAttribute('aria-label', tx('tuMensaje')); send.textContent = tx('enviar'); foot.textContent = tx('pie');
      var priv = lang() === 'en' ? (me.getAttribute('data-privacidad-en') || me.getAttribute('data-privacidad')) : me.getAttribute('data-privacidad');
      if (priv) { var pa = el('a', null, tx('privacidad')); pa.href = priv; pa.target = '_blank'; pa.rel = 'noopener noreferrer'; foot.appendChild(document.createTextNode(' ')); foot.appendChild(pa); }
    }

    // texto → nodos: solo se vuelven enlaces las direcciones http(s)
    function conEnlaces(box, texto) {
      var re = /(https?:\/\/[^\s)]+)/g, last = 0, m;
      while ((m = re.exec(texto))) { if (m.index > last) box.appendChild(document.createTextNode(texto.slice(last, m.index))); var a = el('a', null, m[1]); a.href = m[1]; a.target = '_blank'; a.rel = 'noopener noreferrer'; box.appendChild(a); last = m.index + m[1].length; }
      if (last < texto.length) box.appendChild(document.createTextNode(texto.slice(last)));
    }
    function addMsg(rol, texto, extraCls) { var b = el('div', 'msia-m ' + (extraCls || (rol === 'user' ? 'msia-m--me' : 'msia-m--bot'))); conEnlaces(b, texto); list.appendChild(b); list.scrollTop = list.scrollHeight; return b; }
    function render() { list.textContent = ''; addMsg('assistant', tx('bienvenida')); msgs.forEach(function (m) { addMsg(m.rol, m.texto); }); }
    function typing(on) { var x = list.querySelector('.msia-typing'); if (on && !x) { x = el('div', 'msia-typing'); x.innerHTML = '<i></i><i></i><i></i>'; x.setAttribute('aria-label', tx('escribiendo')); list.appendChild(x); list.scrollTop = list.scrollHeight; } if (!on && x) x.remove(); }
    function aviso(texto) { addMsg('assistant', texto, 'msia-m--err'); }
    function contacto() { return whatsapp ? tx('wa') + whatsapp : ''; }

    function enviar(texto) {
      if (busy || !texto) return; busy = true; send.disabled = true;
      msgs.push({ rol: 'user', texto: texto }); save(); addMsg('user', texto); typing(true);
      var ctrl = new AbortController(), to = setTimeout(function () { ctrl.abort(); }, 30000);
      fetch(api + '/api/chat', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ cliente: cliente, mensajes: msgs, idioma: lang() }), signal: ctrl.signal })
        .then(function (r) { return r.json().catch(function () { return {}; }).then(function (d) { return { ok: r.ok, d: d }; }); })
        .then(function (x) {
          typing(false);
          if (x.ok && x.d.respuesta) { msgs.push({ rol: 'assistant', texto: x.d.respuesta }); save(); addMsg('assistant', x.d.respuesta); return; }
          var e = x.d.error; msgs.pop(); save();
          if (e === 'limite_conversacion') aviso(tx('limConv') + contacto());
          else if (e === 'muy_rapido') aviso(tx('rapido'));
          else if (e === 'limite_dia' || e === 'limite_negocio') aviso(tx('limDia') + contacto());
          else if (e === 'largo') aviso(tx('largo')(x.d.max || MAX_CHARS));
          else aviso(tx('fallo') + contacto());
        })
        .catch(function () { typing(false); msgs.pop(); save(); aviso(tx('conexion') + contacto()); })
        .then(function () { clearTimeout(to); busy = false; send.disabled = false; if (!embed) input.focus(); });
    }
    form.addEventListener('submit', function (e) { e.preventDefault(); var v = input.value.trim(); if (!v) return; input.value = ''; input.style.height = 'auto'; enviar(v); });
    input.addEventListener('keydown', function (e) { if (e.key === 'Enter' && !e.shiftKey) { e.preventDefault(); form.requestSubmit(); } });
    input.addEventListener('input', function () { input.style.height = 'auto'; input.style.height = Math.min(input.scrollHeight, 90) + 'px'; });
    function abrir(v) { if (embed) return; root.classList.toggle('is-open', v); toggle.setAttribute('aria-expanded', v ? 'true' : 'false'); if (v) { list.scrollTop = list.scrollHeight; setTimeout(function () { input.focus(); }, 120); } }
    toggle.addEventListener('click', function () { abrir(!root.classList.contains('is-open')); });
    cerrar.addEventListener('click', function () { abrir(false); });
    nuevo.addEventListener('click', function () { if (busy) return; msgs = []; save(); render(); if (!embed) input.focus(); });
    if (!embed) document.addEventListener('keydown', function (e) { if (e.key === 'Escape') abrir(false); });
    function montar() {
      (embed ? contenedor : document.body).appendChild(root); textos(); render();
      // si la página cambia de idioma, el chat cambia sus textos (y el saludo, mientras no haya empezado a conversar)
      try { new MutationObserver(function () { textos(); if (!msgs.length) render(); }).observe(document.documentElement, { attributes: true, attributeFilter: ['lang'] }); } catch (e) { /* sin observador: el idioma se toma al cargar */ }
    }
    if (document.body) montar(); else document.addEventListener('DOMContentLoaded', montar);
    return { root: root, destruir: function () { if (root.parentNode) root.parentNode.removeChild(root); } };
  }

  // Instalación con etiqueta <script data-cliente=...>: globo flotante
  if (scriptEl && scriptEl.getAttribute('data-cliente')) create(scriptEl, null);

  // Montaje dentro de la página (demos)
  window.MsiaChat = {
    mount: function (o) {
      var attrs = { 'data-cliente': o.cliente, 'data-api': o.api, 'data-titulo': o.titulo, 'data-titulo-en': o.tituloEn, 'data-sub': o.sub, 'data-sub-en': o.subEn, 'data-bienvenida': o.bienvenida, 'data-bienvenida-en': o.bienvenidaEn, 'data-pie': o.pie, 'data-pie-en': o.pieEn, 'data-privacidad': o.privacidad, 'data-privacidad-en': o.privacidadEn, 'data-max': o.max, 'data-whatsapp': o.whatsapp };
      return create({ src: scriptSrc, getAttribute: function (k) { return attrs[k] == null ? null : String(attrs[k]); } }, o.contenedor);
    }
  };
})();
